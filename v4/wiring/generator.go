const (
    indent            = "    "
    generatedFileNote = "// Code generated by melody:wiring:generate. DO NOT EDIT."

    configImportPath             = "github.com/precision-soft/melody/v4/config"
    containerImportPath          = "github.com/precision-soft/melody/v4/container"
    containerContractImportPath  = "github.com/precision-soft/melody/v4/container/contract"
    exceptionImportPath          = "github.com/precision-soft/melody/v4/exception"
    mathImportPath               = "math"
    containerContractImportAlias = "containercontract"
    configImportAlias            = "melodyconfig"
    containerImportAlias         = "melodycontainer"
    exceptionImportAlias         = "melodyexception"
    mathImportAlias              = "math"
)

/* GenerateConfig is the target of a generation, declared once in Go beside the bind set, so the command and a bootstrap program write the same file. */
type GenerateConfig struct {
    PackageName string
    /* FunctionName names the registration function; RegisterGeneratedServices when empty. */
    FunctionName string
    /* ScopedFunctionName names the function the scope-owned registrations are emitted into. It defaults to the container function's name with Scoped appended, and the function is only emitted when something carries the scoped directive. */
    ScopedFunctionName string
    /* BuildTags are the build tags the target binary carries, so a constructor gated on one of them is scanned rather than dropped; the generated file is then specific to those tags and must be built with them. */
    BuildTags []string
}

type GenerateRequest struct {
    ProjectDirectory string
    Config           GenerateConfig
    BindSet          *BindSet
    /* DeclaredParameters is the set of parameter names the application declares. When it is empty the generator cannot check a bind target and says so instead of assuming the target exists. */
    DeclaredParameters map[string]bool
}

type GenerateReport struct {
    ConstructorCount int
    /* ScopedConstructorCount counts the constructors emitted into the scoped registration function, so the command can report the two lifetimes apart. */
    ScopedConstructorCount int
    Skipped                []*SkippedConstructor
    /* SkippedVendorDirectories names the vendor trees the scan stepped over; strict does not fail on them — they cannot contribute services — but the command can name them on request. */
    SkippedVendorDirectories []string
    /* ExcludedFiles names the build-excluded files that hold a constructor candidate; strict does not fail on them, but the command can name them on request so a missing service traces back to the tag it needs. */
    ExcludedFiles   []string
    UnusedBinds     []string
    GlobalBindReach map[string][]string
    /* BindTargetsUnchecked reports that a bind resolved while DeclaredParameters was empty, so its target could not be checked. The command always hands over the running configuration; a direct Generate caller can trip it. */
    BindTargetsUnchecked bool
}

/* Generate scans every declared package and renders the registration source, in gofmt's form. It fails on the first constructor whose scalar argument no bind covers: an unfilled scalar has no safe default, and letting it through would move the failure to a runtime far from its cause. */
func Generate(request *GenerateRequest) (string, *GenerateReport, error) {
    if nil == request || nil == request.BindSet {
        return "", nil, exception.NewError("a bind set is required to generate the wiring", nil, nil)
    }

    functionName := request.Config.FunctionName
    if "" == functionName {
        functionName = "RegisterGeneratedServices"
    }

    scopedFunctionName := request.Config.ScopedFunctionName
    if "" == scopedFunctionName {
        scopedFunctionName = functionName + "Scoped"
    }

    report := &GenerateReport{
        Skipped:                  make([]*SkippedConstructor, 0),
        SkippedVendorDirectories: make([]string, 0),
        ExcludedFiles:            make([]string, 0),
        UnusedBinds:              make([]string, 0),
        GlobalBindReach:          make(map[string][]string),
    }

    usedBinds := make(map[string]bool)

    /* every fixed alias is reserved before any scanned type can claim its name, so a scanned argument from one of these packages renders through the alias the emitted bodies use */
    importAliases := newImportAliasTable()

    /* both names land verbatim in the generated source: a non-identifier, a keyword, the blank identifier or init would not compile or would splice arbitrary tokens into the file */
    if false == token.IsIdentifier(functionName) || "_" == functionName || "init" == functionName {
        return "", nil, exception.NewError(
            "the generated function name cannot be declared and referenced in the generated file",
            map[string]any{
                "function": functionName,
            },
            nil,
        )
    }

    if false == token.IsIdentifier(scopedFunctionName) || "_" == scopedFunctionName || "init" == scopedFunctionName {
        return "", nil, exception.NewError(
            "the generated scoped function name cannot be declared and referenced in the generated file",
            map[string]any{
                "function": scopedFunctionName,
            },
            nil,
        )
    }

    /* the two functions share one file, so one name cannot serve both */
    if functionName == scopedFunctionName {
        return "", nil, exception.NewError(
            "the generated function names must differ, or the file declares the same function twice",
            map[string]any{
                "function": functionName,
            },
            nil,
        )
    }

    if false == token.IsIdentifier(request.Config.PackageName) || "_" == request.Config.PackageName {
        return "", nil, exception.NewError(
            "the generated package name is not a usable Go package name",
            map[string]any{
                "package": request.Config.PackageName,
            },
            nil,
        )
    }

    /* the generated function shares its file with the fixed import aliases and the identifiers the provider bodies spell, so a name claiming one of them cannot compile */
    if true == importAliases.takenAlias[functionName] ||
        containerContractImportAlias == functionName ||
        containerImportAlias == functionName ||
        configImportAlias == functionName ||
        exceptionImportAlias == functionName ||
        mathImportAlias == functionName {
        return "", nil, exception.NewError(
            "the generated function name collides with an identifier the generated file spells",
            map[string]any{
                "function": functionName,
            },
            nil,
        )
    }

    if true == importAliases.takenAlias[scopedFunctionName] ||
        containerContractImportAlias == scopedFunctionName ||
        containerImportAlias == scopedFunctionName ||
        configImportAlias == scopedFunctionName ||
        exceptionImportAlias == scopedFunctionName ||
        mathImportAlias == scopedFunctionName {
        return "", nil, exception.NewError(
            "the generated scoped function name collides with an identifier the generated file spells",
            map[string]any{
                "function": scopedFunctionName,
            },
            nil,
        )
    }

    importAliases.reserveIdentifier(functionName)
    importAliases.reserveIdentifier(scopedFunctionName)
    importAliases.reserve(containerContractImportPath, containerContractImportAlias)
    importAliases.reserve(containerImportPath, containerImportAlias)
    importAliases.reserve(configImportPath, configImportAlias)
    importAliases.reserve(exceptionImportPath, exceptionImportAlias)
    importAliases.reserve(mathImportPath, mathImportAlias)

    providerBlocks := make([]string, 0)
    scopedProviderBlocks := make([]string, 0)
    unusedDirectiveBinds := make([]string, 0)

    /* two constructors registering under one container key would panic at the first boot of the generated file, so the collision is keyed as the emitted registration keys it, a named registration claiming its constant and the returned type, and fails at generation naming both sites. A constant's value is not read, so two constants holding one value stay out of reach. */
    registrationSites := make(map[string]*Constructor)

    /* every identity of every container registration, so a scoped registration that shares one is emitted with ReplacesContainerService, which the container requires for a deliberate scoped shadow; the scoped render is deferred until the whole set is known */
    containerIdentityKeys := make(map[string]bool)
    pendingScoped := make([]pendingScopedProvider, 0)

    for _, packageBinding := range request.BindSet.Packages() {
        /* an empty import path renders an import of "", and an empty directory scans the whole project tree as one package */
        if "" == packageBinding.ImportPath() || "" == packageBinding.Directory() {
            return "", nil, exception.NewError(
                "a package binding must declare both an import path and a directory",
                map[string]any{
                    "importPath": packageBinding.ImportPath(),
                    "directory":  packageBinding.Directory(),
                },
                nil,
            )
        }

        scanResult, scanErr := Scan(ScanRequest{ProjectDirectory: request.ProjectDirectory, PackageBinding: packageBinding, BuildTags: request.Config.BuildTags})
        if nil != scanErr {
            return "", nil, scanErr
        }

        report.Skipped = append(report.Skipped, scanResult.Skipped...)
        report.SkippedVendorDirectories = append(report.SkippedVendorDirectories, scanResult.SkippedVendorDirectories...)
        report.ExcludedFiles = append(report.ExcludedFiles, scanResult.ExcludedFiles...)


        for _, constructor := range scanResult.Constructors {
            registrationKeys := registrationKeysFor(constructor)
            for _, registrationKey := range registrationKeys {
                existing, taken := registrationSites[registrationKey]
                if false == taken {
                    continue
                }

                return "", nil, exception.NewError(
                    "two constructors register the same service",
                    map[string]any{
                        "first":  existing.Name + " (" + existing.File + ":" + strconv.Itoa(existing.Line) + ")",
                        "second": constructor.Name + " (" + constructor.File + ":" + strconv.Itoa(constructor.Line) + ")",
                    },
                    nil,
                )
            }

            for _, registrationKey := range registrationKeys {
                registrationSites[registrationKey] = constructor
            }

            resolvedArguments, constructorUnusedDirectiveBinds, resolveErr := resolveArguments(
                constructor,
                packageBinding,
                request,
                usedBinds,
                report,
            )
            if nil != resolveErr {
                return "", nil, resolveErr
            }

            unusedDirectiveBinds = append(unusedDirectiveBinds, constructorUnusedDirectiveBinds...)

            if true == constructor.IsScoped {
                /* deferred until every container identity is known */
                pendingScoped = append(
                    pendingScoped,
                    pendingScopedProvider{
                        constructor:       constructor,
                        resolvedArguments: resolvedArguments,
                    },
                )

                report.ScopedConstructorCount = report.ScopedConstructorCount + 1

                continue
            }

            for _, identityKey := range serviceIdentityKeys(constructor) {
                containerIdentityKeys[identityKey] = true
            }

            providerBlocks = append(
                providerBlocks,
                renderProvider(constructor, resolvedArguments, importAliases, false),
            )

            report.ConstructorCount = report.ConstructorCount + 1
        }
    }

    /* a scoped registration whose name or type the container also claims is emitted with ReplacesContainerService */
    for _, pending := range pendingScoped {
        replacesContainerService := false
        for _, identityKey := range serviceIdentityKeys(pending.constructor) {
            if true == containerIdentityKeys[identityKey] {
                replacesContainerService = true

                break
            }
        }

        scopedProviderBlocks = append(
            scopedProviderBlocks,
            renderProvider(pending.constructor, pending.resolvedArguments, importAliases, replacesContainerService),
        )
    }

    report.UnusedBinds = collectUnusedBinds(request.BindSet, usedBinds, unusedDirectiveBinds)

    source := renderFile(
        request.Config.PackageName,
        functionName,
        scopedFunctionName,
        importAliases,
        providerBlocks,
        scopedProviderBlocks,
    )

    /* the file lands in the consumer's project, whose tools read Go in gofmt's form: the rendered source goes through it before anyone sees it, so the file written, the source printed and the source a staleness check regenerates in memory are one and the same, and a consumer that formats the file finds nothing to change */
    formatted, formatErr := format.Source([]byte(source))
    if nil != formatErr {
        return "", nil, exception.NewError(
            "the rendered wiring source is not valid Go and could not be formatted; nothing was written",
            map[string]any{"source": source},
            formatErr,
        )
    }

    return string(formatted), report, nil
}

/* registrationKeysFor derives every key the emitted registration claims in the container, each with its lifetime, so two constructors claiming one key fail at generation. The two lifetimes do not collide: a scoped registration deliberately shadows the container one and is emitted with ReplacesContainerService. */
func registrationKeysFor(constructor *Constructor) []string {
    lifetime := "container"
    if true == constructor.IsScoped {
        lifetime = "scoped"
    }

    keys := serviceIdentityKeys(constructor)
    for index, identityKey := range keys {
        keys[index] = lifetime + " " + identityKey
    }

    return keys
}

/* serviceIdentityKeys are the identities a registration claims without its lifetime, what the container refuses a duplicate on. The returned type is always among them, since the container's default option registers the type strictly as well, so a named registration claims its constant and its type. A type registration's derived name is not keyed, since a constant's value is not read from the source. */
func serviceIdentityKeys(constructor *Constructor) []string {
    keys := make([]string, 0, 2)

    if "" != constructor.ServiceNameIdentifier {
        keys = append(keys, "name "+constructor.ImportPath+"."+constructor.ServiceNameIdentifier)
    }

    return append(keys, serviceTypeIdentityKey(constructor))
}

/* serviceTypeIdentityKey keys the returned type, import path and bare name, canonicalized as the container's canonicalServiceType does: T and *T both register as *T, so a package declaring `func() Foo` and `func() *Foo` fails at generation. */
func serviceTypeIdentityKey(constructor *Constructor) string {
    typeName := constructor.ReturnType.Expression

    for true == strings.HasPrefix(typeName, "*") {
        typeName = strings.TrimPrefix(typeName, "*")
    }

    if separatorIndex := strings.Index(typeName, "."); 0 <= separatorIndex {
        typeName = typeName[separatorIndex+1:]
    }

    /* the single star is the canonical form, for a value type and its pointer alike */
    return "type *" + constructor.ReturnType.ImportPath + "." + typeName
}

type resolvedArgument struct {
    argument      *Argument
    parameterName string
    variableName  string
}

type pendingScopedProvider struct {
    constructor       *Constructor
    resolvedArguments []*resolvedArgument
}

/* viewTypes are the runtime-bound views, a value of one request, run or delivery that no provider registers, so a constructor asking for one is refused at generation rather than at its first resolution; every view the framework declares is listed here */
var viewTypes = map[string]bool{
    "github.com/precision-soft/melody/integrations/bunorm/v4.Bound": true,
    "github.com/precision-soft/melody/v4/cache.Bound":               true,
    "github.com/precision-soft/melody/v4/httpclient.Bound":          true,
    "github.com/precision-soft/melody/v4/security.BoundTokenStore":  true,
    "github.com/precision-soft/melody/v4/storage.Bound":             true,
}

func isViewType(typeReference *TypeReference) bool {
    if nil == typeReference {
        return false
    }

    expression := typeReference.Expression

    return viewTypes[typeReference.ImportPath+"."+expression[strings.LastIndex(expression, ".")+1:]]
}

/* requestLifetimeTypes are the values of one request a process service built once would keep past it, so a constructor not declared scoped is refused one at generation */
var requestLifetimeTypes = map[string]bool{
    "github.com/precision-soft/melody/v4/container/contract.Scope":        true,
    "github.com/precision-soft/melody/v4/http/contract.Request":           true,
    "github.com/precision-soft/melody/v4/http/contract.RequestContext":    true,
    "github.com/precision-soft/melody/v4/http/contract.Response":          true,
    "github.com/precision-soft/melody/v4/security/contract.Token":         true,
    "github.com/precision-soft/melody/v4/session/contract.Session":        true,
}

/* keptResolutionTypes are the field types through which a service keeps the resolution that built it */
var keptResolutionTypes = map[string]bool{
    "context.CancelFunc":                    true,
    "context.Context":                       true,
    containerContractImportPath + ".Runtime": true,
}

/* refuseLifetime refuses what a constructor not declared scoped would keep of the resolution that built it, and a keeps-context directive that admits nothing */
func refuseLifetime(constructor *Constructor) error {
    for _, argument := range constructor.Arguments {
        if true == argument.Type.IsPointer && true == isNamedType(argument.Type, "context", "Context") {
            return lifetimeRefusal("a pointer to a context cannot be resolved: take context.Context", constructor, argument, nil)
        }
    }

    if true == constructor.IsScoped {
        if true == constructor.KeepsContext {
            return lifetimeRefusal("a keeps-context directive on a scoped constructor admits nothing: remove it", constructor, nil, nil)
        }

        return nil
    }

    takesResolution := false
    for _, argument := range constructor.Arguments {
        if true == requestLifetimeTypes[structKey(argument.Type)] {
            return lifetimeRefusal("a process service cannot be built from a value of one request: mark the constructor //melody:scoped, or take the value at each call", constructor, argument, nil)
        }

        if true == argument.IsContext || true == argument.IsRuntime {
            takesResolution = true
        }
    }

    var keptField *FieldReference
    if true == takesResolution {
        for _, field := range constructor.ReturnFields {
            if true == keptResolutionTypes[structKey(field.Type)] {
                keptField = field

                break
            }
        }
    }

    if nil == keptField {
        if true == constructor.KeepsContext {
            return lifetimeRefusal("a keeps-context directive on a constructor that keeps no context of its resolution admits nothing: remove it", constructor, nil, nil)
        }

        return nil
    }

    if true == constructor.KeepsContext {
        return nil
    }

    return lifetimeRefusal("a process service cannot keep the context of the resolution that built it: mark the constructor //melody:scoped, or take the context at each call", constructor, nil, keptField)
}

func lifetimeRefusal(message string, constructor *Constructor, argument *Argument, field *FieldReference) error {
    context := map[string]any{
        "constructor": constructor.Name,
        "file":        constructor.File,
        "line":        constructor.Line,
        "door":        keepsContextDirective,
    }

    if nil != argument {
        context["argument"] = argument.Name
        context["type"] = argument.Type.Expression
    }

    if nil != field {
        context["field"] = field.Name
        context["type"] = field.Type.Expression
    }

    return exception.NewError(message, context, nil)
}

func resolveArguments(
    constructor *Constructor,
    packageBinding *PackageBinding,
    request *GenerateRequest,
    usedBinds map[string]bool,
    report *GenerateReport,
) ([]*resolvedArgument, []string, error) {
    if lifetimeErr := refuseLifetime(constructor); nil != lifetimeErr {
        return nil, nil, lifetimeErr
    }

    resolvedArguments := make([]*resolvedArgument, 0, len(constructor.Arguments))
    matchedDirectiveBinds := make(map[string]bool)

    for _, argument := range constructor.Arguments {
        resolved := &resolvedArgument{
            argument:     argument,
            variableName: argument.Name,
        }

        if true == isViewType(argument.Type) {
            return nil, nil, exception.NewError(
                "a runtime-bound view is not a service: bind it inside the method, from the runtime",
                map[string]any{
                    "constructor": constructor.Name,
                    "argument":    argument.Name,
                    "type":        argument.Type.Expression,
                    "file":        constructor.File,
                    "line":        constructor.Line,
                },
                nil,
            )
        }

        if false == argument.IsScalar {
            resolvedArguments = append(resolvedArguments, resolved)

            continue
        }

        parameterName, bindScope, found := lookupBind(constructor, packageBinding, request.BindSet, argument.Name)
        if false == found {
            return nil, nil, exception.NewError(
                "no bind covers a scalar constructor argument",
                map[string]any{
                    "constructor": constructor.Name,
                    "argument":    argument.Name,
                    "type":        argument.Type.Expression,
                    "file":        constructor.File,
                    "line":        constructor.Line,
                },
                nil,
            )
        }

        /* an empty declared-parameter set disables this check, which the result reports; the flag is raised only when a bind actually went unchecked */
        if 0 == len(request.DeclaredParameters) {
            report.BindTargetsUnchecked = true
        }

        if 0 < len(request.DeclaredParameters) && false == request.DeclaredParameters[parameterName] {
            return nil, nil, exception.NewError(
                "a bind points at a parameter the application does not declare",
                map[string]any{
                    "constructor": constructor.Name,
                    "argument":    argument.Name,
                    "parameter":   parameterName,
                    "file":        constructor.File,
                    "line":        constructor.Line,
                },
                nil,
            )
        }

        if bindScopeDirective == bindScope {
            matchedDirectiveBinds[argument.Name] = true
        }

        if bindScopeGlobal == bindScope {
            usedBinds[globalBindKey(argument.Name)] = true

            report.GlobalBindReach[argument.Name] = append(
                report.GlobalBindReach[argument.Name],
                constructor.Name,
            )
        }

        if bindScopePackage == bindScope {
            usedBinds[packageBindKey(packageBinding.ImportPath(), argument.Name)] = true
        }

        resolved.parameterName = parameterName

        resolvedArguments = append(resolvedArguments, resolved)
    }

    /* a directive bind naming an argument the constructor does not have, or a service argument, is reported rather than vanishing */
    unusedDirectiveBinds := make([]string, 0)
    for bindName := range constructor.DirectiveBinds {
        if false == matchedDirectiveBinds[bindName] {
            unusedDirectiveBinds = append(unusedDirectiveBinds, constructor.Name+"."+bindName)
        }
    }

    return resolvedArguments, unusedDirectiveBinds, nil
}

type bindScopeKind int

const (
    bindScopeDirective bindScopeKind = iota
    bindScopePackage
    bindScopeGlobal
)

func lookupBind(
    constructor *Constructor,
    packageBinding *PackageBinding,
    bindSet *BindSet,
    argumentName string,
) (string, bindScopeKind, bool) {
    if parameterName, exists := constructor.DirectiveBinds[argumentName]; true == exists {
        return parameterName, bindScopeDirective, true
    }

    if parameterName, exists := packageBinding.Bind(argumentName); true == exists {
        return parameterName, bindScopePackage, true
    }

    if parameterName, exists := bindSet.GlobalBind(argumentName); true == exists {
        return parameterName, bindScopeGlobal, true
    }

    return "", bindScopeGlobal, false
}

func globalBindKey(argumentName string) string {
    return "global:" + argumentName
}

func packageBindKey(importPath string, argumentName string) string {
    return "package:" + importPath + ":" + argumentName
}

func collectUnusedBinds(bindSet *BindSet, usedBinds map[string]bool, unusedDirectiveBinds []string) []string {
    unused := make([]string, 0)

    unused = append(unused, unusedDirectiveBinds...)

    for _, argumentName := range bindSet.GlobalBindNames() {
        if false == usedBinds[globalBindKey(argumentName)] {
            unused = append(unused, argumentName)
        }
    }

    for _, packageBinding := range bindSet.Packages() {
        for _, argumentName := range packageBinding.BindNames() {
            if false == usedBinds[packageBindKey(packageBinding.ImportPath(), argumentName)] {
                unused = append(unused, packageBinding.ImportPath()+"."+argumentName)
            }
        }
    }

    sort.Strings(unused)

    return unused
}
