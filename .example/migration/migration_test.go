/* the two sets are ONE migration each because the example has one state, so what is pinned here is the CONTENT of each migration, which statements it emits and in what order, rather than how many steps the schema is spread over; a count could not see a set emitted backwards. */
func TestMigrationsHoldOneSchemaMigrationPerDatabase(t *testing.T) {
    sorted := Migrations.Sorted()
    if 1 != len(sorted) {
        t.Fatalf("expected the catalog set to hold one migration, got %d", len(sorted))
    }
    if "20260907000001" != sorted[0].Name {
        t.Fatalf("expected the catalog migration to be 20260907000001, got %s", sorted[0].Name)
    }
    if nil == sorted[0].Up || nil == sorted[0].Down {
        t.Fatalf("expected migration %s to carry both directions", sorted[0].Name)
    }

    journalSorted := JournalMigrations.Sorted()
    if 1 != len(journalSorted) {
        t.Fatalf("expected the journal set to hold one migration, got %d", len(journalSorted))
    }
    if "20260907000002" != journalSorted[0].Name {
        t.Fatalf("expected the journal migration to be 20260907000002, got %s", journalSorted[0].Name)
    }
    if nil == journalSorted[0].Up || nil == journalSorted[0].Down {
        t.Fatalf("expected migration %s to carry both directions", journalSorted[0].Name)
    }
}

